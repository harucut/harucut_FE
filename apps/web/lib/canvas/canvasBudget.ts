/**
 * **한 캔버스가 얼마나 커도 되는가** — 이 저장소에서 그 답을 갖는 단 한 곳.
 *
 * 왜 따로 있나: 예전에는 이 상한이 `composeFrame.ts`(네컷 합성 900여 줄) 안에 있었다.
 * 그런데 상한이 필요한 쪽은 합성만이 아니다 — 프로필 사진 업로드와 사진 가져오기가 쓰는
 * `lib/imageDecode.ts` 도 같은 선을 봐야 하는데, 그러자고 잎 유틸이 합성 모듈을 통째로
 * 끌어오게 됐다. 숫자를 양쪽에 하나씩 두면 한쪽만 고쳐지고, 그때 갈라지는 쪽이 하필
 * 「조용히 빈 캔버스」 경로다. 그래서 재는 것(캔버스 하나의 크기)만 남긴 잎으로 뺐다.
 * 여기는 아무것도 import 하지 않는다 — 그게 이 파일의 존재 이유다.
 *
 * ## 확인된 것
 *
 * 우리 레이아웃은 넷 다 가장 긴 변이 6000 이고(`constants/frameLayouts.ts`), 그중 둘이
 * **24MP**(6000×4000, 4000×6000)라 넓이 예산에 걸린다. 클래식 2000×6000 은 12MP 라
 * 그대로 나간다. 2026-09-01 데스크톱 WebKit 에서는 24MP 캔버스가 멀쩡히 그려지고
 * 인코딩됐다 — **데스크톱에서는 재현되지 않는다**는 것까지만 안다.
 *
 * ## 가정 — 아래 두 값은 어느 것도 실기기로 확인한 적이 없다
 *
 * 근거는 하나뿐이다: 「iOS Safari 는 캔버스 넓이가 2^24(16,777,216)px 를 넘으면 오류 없이
 * 빈 캔버스를 그리거나 toBlob 이 null 을 준다」는 이야기. 우리는 그 이야기를 듣고 거기에
 * 딱 붙이지 않고 조금 아래에 예산을 두었다.
 *
 * 그런데 2^24 은 정확히 4096² 이라, **원래 제약이 넓이 상한인지 변 상한(4096px)인지
 * 이 근거만으로는 갈리지 않는다.** 그래서 값을 이렇게 나눠 뒀다.
 *
 *  - `MAX_CANVAS_PIXELS` — 넓이. 위 이야기 그대로다.
 *  - `MAX_CANVAS_EDGE` — 가장 긴 변. **기기에서 잰 값이 아니다.** 우리가 실제로 그려서
 *    내보내는 가장 큰 레이아웃의 긴 변(6000)이다. 캔버스에 들어오는 그림이 이제 우리
 *    레이아웃만이 아니라 **사용자가 고른 사진**이라서 붙였다 — 파노라마(예: 25344×2048)는
 *    넓이 예산을 통과하면서 한 변이 1만 px 을 넘는다. 그런 크기를 우리는 한 번도 그려
 *    본 적이 없다.
 *
 * 변 상한 가설이 맞다면 6000 으로는 못 막는다. 그때 넣어야 할 값은 4096 인데, 그러면
 * 클래식 2000×6000 이 1365×4096(12MP → 5.6MP)이 되어 **이 앱의 주 결과물이 화소의 절반을
 * 잃는다.** 근거가 「2^24 이 4096² 이기도 하다」 하나뿐인 채로 그 값을 치르지 않기로 했다.
 * 대신 그 가설이 맞다면 지금도 아이폰 비회원 합성(클래식 2000×6000)이 빈 이미지로
 * 끝나고 있을 것이다 — 실기기에서 그것부터 확인하면 갈린다. 확인 전까지는 여기 4096 을
 * 넣지 않는다.
 *
 * ## 그래도 상한을 걷지 않는 이유
 *
 * 비용이 비대칭이라서다. 가정이 맞는데 걷으면 완성 단계가 빈 이미지로 끝나고, 가정이
 * 틀린 채 두면 해상도를 조금 잃을 뿐이다. 값을 올리거나 내리려면 진짜 아이폰에서
 * 재현/반증부터 해야 한다.
 */

/** 캔버스 하나가 가질 수 있는 화소 수. 위 「가정」 참고. */
export const MAX_CANVAS_PIXELS = 16_000_000;

/**
 * 캔버스 한 변의 최대 길이. 우리 레이아웃의 가장 긴 변에서 온 값이지 기기에서 잰 값이
 * 아니다(위 「가정」 참고). `constants/frameLayouts.ts` 에 이보다 긴 레이아웃이 생기면
 * `canvasBudget.test.ts` 가 깨진다 — 그때 이 값을 같이 정하라는 뜻이다.
 */
export const MAX_CANVAS_EDGE = 6000;

/**
 * 큰 그림을 **나눠 그릴 때 임시 캔버스 하나**가 가질 화소 수.
 *
 * 위 두 값과 성격이 다르다 — 기기가 못 그리는 선(가정)이 아니라 **우리가 한 번에 들기로
 * 한 메모리**다. `lib/imageDecode.ts` 가 libheif 가 준 원본 RGBA 버퍼를 타일로 잘라
 * 캔버스에 얹을 때 쓴다.
 *
 * 100만 화소 = RGBA 4MB. **재서 고른 값이 아니다.** 목적지 캔버스(예산을 꽉 채우면
 * 16MP·64MB)에 비해 무시할 만큼 작으면서, 아이폰 48MP 사진이 타일 63장으로 끝나는 크기다
 * (그 장수는 세어 봤다). 더 잘게 자르면 호출 수만 늘고 타일 경계(그 줄에서 필터가 이웃
 * 타일을 못 본다)가 그만큼 늘어난다.
 *
 * 그래도 여기 둔 이유는 위 두 값과 같다 — 타일도 캔버스라 이 값이 예산을 넘으면 그 임시
 * 캔버스가 조용히 빈 채로 남는다. 숫자를 두 파일에 나눠 두면 그때 갈라진다.
 */
export const MAX_TILE_PIXELS = 1_000_000;

/**
 * 예산 안에 들어가는 축소 배율. 넓이·변 둘 다 넘지 않을 때만 1이다.
 *
 * 둘 중 **더 많이 줄이는 쪽**을 쓴다. 비율은 그대로라 그림이 늘어나지 않는다.
 */
export function fitCanvasScale(width: number, height: number) {
  const pixels = width * height;
  const areaScale =
    pixels <= MAX_CANVAS_PIXELS ? 1 : Math.sqrt(MAX_CANVAS_PIXELS / pixels);

  const longestEdge = Math.max(width, height);
  const edgeScale = longestEdge <= MAX_CANVAS_EDGE ? 1 : MAX_CANVAS_EDGE / longestEdge;

  return Math.min(areaScale, edgeScale);
}
